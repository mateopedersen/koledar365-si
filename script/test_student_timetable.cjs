const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const {webcrypto}=require('node:crypto');
const context={window:{},crypto:webcrypto,Intl,Date,TextEncoder,Error,Array,Object,String,Number,JSON,Math};
vm.runInNewContext(fs.readFileSync('app/assets/javascripts/student_timetable_core.js','utf8'),context);
const core=context.window.K365StudentCore;
const lesson=(id,day,subject,start='08:00',end='08:45')=>({id,day,subject,start,end,room:'12',teacher:'N. Novak',color:'blue'});
const state={version:1,lessons:[lesson('math',1,'Matematika'),lesson('sl',2,'Slovenščina','09:00','09:45')],tasks:[{id:'hw',title:'Vaja, 1; 2',due:'2027-03-29',subject:'Matematika',kind:'homework',priority:'high',done:false}]};
assert.equal(core.validateLesson(lesson('x',5,'Zgodovina')).day,5);
assert.throws(()=>core.validateLesson(lesson('x',6,'Napačen dan')),/ponedeljka do petka/);
assert.throws(()=>core.validateLesson(lesson('x',1,'Neveljaven čas','09:00','08:45')),/Konec ure/);
assert.equal(core.validateTask(state.tasks[0]).kind,'homework');
assert.throws(()=>core.validateTask({...state.tasks[0],due:'2027-02-30'}),/veljaven datum/);
assert.throws(()=>core.cleanState({version:1,lessons:[lesson('same',1,'Matematika'),lesson('same',2,'Slovenščina')],tasks:[]}),/podvojene zapise/);
assert.throws(()=>core.cleanState({version:1,lessons:[lesson('first',1,'Matematika','08:00','09:00'),lesson('second',1,'Slovenščina','08:45','09:30')],tasks:[]}),/prekrivajoči se uri/);
assert.equal(core.cleanState({version:1,lessons:[{...lesson('x',1,'Zgodovina'),color:'pink'}],tasks:[]}).lessons[0].color,'blue');
assert.equal(core.utcForLjubljana('2027-01-04','08:00'),'20270104T070000Z');
assert.equal(core.utcForLjubljana('2027-03-29','08:00'),'20270329T060000Z');
assert.throws(()=>core.utcForLjubljana('2027-03-28','02:30'),/poletni ali zimski čas/);
const ics=core.buildIcs(state,'2027-03-22','2027-03-29',new Date('2026-10-22T00:00:00Z'));
assert.equal((ics.match(/BEGIN:VEVENT/g)||[]).length,4);
assert.match(ics,/DTSTART:20270329T060000Z/);
assert.match(ics,/SUMMARY:Domača naloga: Vaja\\, 1\\; 2/);
assert.match(ics,/DTEND;VALUE=DATE:20270330/);
assert.match(ics,/DESCRIPTION:Učilnica: 12\\nUčitelj\/\-ica: N\. Novak/);
for(const line of ics.split('\r\n'))assert.ok(Buffer.byteLength(line,'utf8')<=75,`ICS continuation line is too long: ${Buffer.byteLength(line,'utf8')} bytes`);
const folded=core.foldLine('Predmet č'.repeat(10));
for(const line of folded.split('\r\n'))assert.ok(Buffer.byteLength(line,'utf8')<=75,`Folded ICS line exceeds 75 octets: ${Buffer.byteLength(line,'utf8')}`);
assert.throws(()=>core.buildIcs(state,'2027-01-01','2028-01-10'),/krajše od enega šolskega leta/);
console.log('Student timetable validation, Ljubljana timezone ICS export and RFC line folding passed.');
