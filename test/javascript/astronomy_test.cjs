const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const context = { Intl, Date };
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(root,'app/assets/javascripts/astronomy.js'),'utf8'),context);
const api = context.AstronomyTools;
const data = JSON.parse(fs.readFileSync(path.join(root,'data/astronomy/events-2026-2030.json'),'utf8'));
assert.equal(api.timeLabel('2026-10-25T00:30:00Z',true),'02:30 CEST');
assert.equal(api.timeLabel('2026-10-25T01:30:00Z',true),'02:30 CET');
assert.equal(api.timeLabel('2027-08-02T09:14:58.544Z',true),'11:15 CEST');
assert.equal(api.countdown('2026-10-26T04:12:00Z',Date.parse('2026-10-25T04:12:00Z')),'1 dan · 0 h · 0 min');
assert.equal(api.nextEclipse(data.solar,'ljubljana',Date.parse('2026-10-21T00:00:00Z')).date,'2027-08-02');
assert.equal(api.nextEclipse(data.lunar,'ljubljana',Date.parse('2026-10-21T00:00:00Z')).date,'2027-02-21');
assert.equal(api.nextEclipse(data.solar,'maribor',Date.parse('2026-08-12T18:13:00Z')).date,'2027-08-02');
assert.equal(api.nextEclipse(data.solar,'ljubljana',Date.parse('2031-01-01T00:00:00Z')),undefined);
const season = api.nextPerseids(data.perseids,'ljubljana',Date.parse('2027-08-13T12:00:00Z'));
assert.equal(season.year,2027);
assert.equal(api.nextNight(season,'ljubljana',Date.parse('2027-08-13T12:00:00Z')).date,'2027-08-13');
assert.equal(api.nextPerseids(data.perseids,'ljubljana',Date.parse('2027-08-14T12:00:00Z')).year,2028);
const phases=[{utc:'2026-10-26T04:12:00Z'},{utc:'2026-11-24T14:53:00Z'}];
assert.equal(api.nextMoon(phases,Date.parse('2026-10-26T04:12:00Z')),phases[1]);
console.log('Astronomy browser calculations: 12 timezone, rounding, rollover and visibility checks passed.');
